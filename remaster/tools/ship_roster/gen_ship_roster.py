PLAYABLE_ROLES = {0, 1, 2, 3, 4, 5, 9}
MAJOR = {"Federation", "Klingon", "Romulan", "Cardassian", "Ferengi"}


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def round10(v):
    return (v + 5) // 10 * 10


def attack_scale(t):
    return 250 + 50 * t + 25 * t * t


def derive(s):
    fname, race, hull_base, shield_base, cost_pct, prefix = FACTIONS[s["faction"]]
    eng_role, size, upkeep, speed, rng, sensors, role_cost = ROLES[s["role"]]
    size = s.get("size", size)
    t = s["tier"]
    points = 0
    torp = 0
    for wtype, count, arc in s["weapons"]:
        p = WEAPONS[wtype][0] * count * ARCS[arc] // 100
        points += p
        if WEAPONS[wtype][1]:
            torp += p
    attack = points * attack_scale(t) // 100
    torp_pct = (torp * 100 // points) if points else 0
    hull = hull_base * size // 100 * (100 + 5 * t) // 100
    shields = shield_base * size // 100 * (100 + 6 * t) // 100
    cloak = bool(s.get("cloak", False))
    base = 1800 * size // 100 * (100 + 20 * t + t * t) // 100 + 2 * attack
    cost = base * cost_pct // 100 * role_cost // 100
    if cloak:
        cost = cost * 110 // 100
        upkeep = upkeep * 110 // 100
    cost = max(100, round10(cost))
    L = clamp(t, 0, 10)
    if eng_role in (0,):
        off = [-1, 0, -1, -1, 0, -1]
    elif eng_role == 5:
        off = [0, -1, 0, -1, -1, -9]
    elif eng_role == 9:
        off = [-1, -1, 0, -1, 0, -9]
    else:
        off = [-1, 0, 0, 0, 0, 1]
    tech = [clamp(L + o, 1, 10) for o in off]
    kind = s.get("kind", "Canon")
    buildable = s.get("buildable", True) and kind == "Canon" and s["faction"] in MAJOR and eng_role in PLAYABLE_ROLES
    return dict(
        id=s["id"], key=f"ship.{prefix}.{s['key']}", faction=s["faction"], raceId=race, minorId=MINOR_ID.get(s["faction"], 0),
        roleName=ROLE_LABEL[s["role"]], cls=s["cls"], hullRole=s["role"], engineRole=eng_role, era=s["era"], tier=t,
        tech=tech, cost=cost, buildTurns=max(1, -(-cost // 600)), upkeep=upkeep, hull=max(1, hull), shields=shields,
        attack=attack, torpPct=torp_pct, weapons=s["weapons"], speed=s.get("speed", speed), range=s.get("range", rng),
        sensors=s.get("sensors", sensors), cloak=cloak, kind=kind, source=s["source"], buildable=buildable, desc=s["desc"],
        factionName=fname, points=points,
    )


def cstr(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_header(rows):
    out = []
    out.append("// GENERATED by remaster/tools/ship_roster/gen_ship_roster.py -- do not edit by hand.")
    out.append("// Expanded ship roster data (docs/SHIP-ROSTER.md). Descriptions are original remaster text.")
    out.append("#pragma once")
    out.append('#include "ShipRosterTypes.h"')
    out.append("namespace botf::roster {")
    out.append(f"inline constexpr std::array<RosterClass, {len(rows)}> ExpandedRoster{{{{")
    for r in rows:
        w = [f"{{WeaponType::{t}, {c}, FiringArc::{a}}}" for t, c, a in r["weapons"]]
        while len(w) < 4:
            w.append("{WeaponType::None, 0, FiringArc::Forward}")
        tech = ", ".join(str(x) for x in r["tech"])
        out.append(
            f"    {{{r['id']}, {cstr(r['key'])}, Faction::{r['faction']}, {r['raceId']}, {r['minorId']}, {cstr(r['roleName'])}, "
            f"{cstr(r['cls'])}, HullRole::{r['hullRole']}, {r['engineRole']}, Era::{r['era']}, {r['tier']}, {{{tech}}}, "
            f"{r['cost']}, {r['buildTurns']}, {r['upkeep']}, {r['hull']}, {r['shields']}, {r['attack']}, {r['torpPct']}, "
            f"{{{{{', '.join(w)}}}}}, {len(r['weapons'])}, {r['speed']}, {r['range']}, {r['sensors']}, {str(r['cloak']).lower()}, "
            f"SourceKind::{r['kind']}, {cstr(r['source'])}, {str(r['buildable']).lower()},\n     {cstr(r['desc'])}}},")
    out.append("}};")
    out.append("} // namespace botf::roster")
    return "\n".join(out) + "\n"


def weapons_text(ws):
    return "; ".join(f"{c}x {t} ({a})" for t, c, a in ws) or "none"


def emit_table(rows):
    lines = ["| Id | Faction | Class | Role | Era | Tier | Tech (Bio/Com/Con/Ene/Pro/Wea) | Cost | Turns | Upkeep | Hull | Shields | Attack | Weapons | Spd/Rng/Sen | Cloak | Build | Source | assetKey |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        build = "yes" if r["buildable"] else "data"
        src = r["source"] if r["kind"] != "ModDerived" else "mod-derived (see notes)"
        if r["kind"] == "Kelvin":
            src = "Kelvin: " + src
        lines.append(
            f"| {r['id']} | {r['factionName']} | {r['cls']} | {r['roleName']} | {r['era']} | {r['tier']} | {'/'.join(map(str, r['tech']))} | "
            f"{r['cost']} | {r['buildTurns']} | {r['upkeep']} | {r['hull']} | {r['shields']} | {r['attack']} | {weapons_text(r['weapons'])} | "
            f"{r['speed']}/{r['range']}/{r['sensors']} | {'yes' if r['cloak'] else '-'} | {build} | {src} | `{r['key']}` |")
    counts = {}
    for r in rows:
        c = counts.setdefault(r["factionName"], [0, 0])
        c[0] += 1
        c[1] += 1 if r["buildable"] else 0
    lines.append("")
    lines.append("| Faction | Classes | Buildable in Remastered |")
    lines.append("|---|---|---|")
    for name, (n, b) in counts.items():
        lines.append(f"| {name} | {n} | {b} |")
    lines.append(f"| **Total** | **{len(rows)}** | **{sum(1 for r in rows if r['buildable'])}** |")
    return "\n".join(lines)


def emit_manifest(rows):
    weapons = sorted({t for r in rows for t, _, _ in r["weapons"]})
    return json.dumps({
        "comment": "Template for the local HD asset manifest. Paths are placeholders; models and audio are not in the repo.",
        "ships": {r["key"]: {"model": "", "hullTexture": "", "engineAudio": "", "ambientAudio": ""} for r in rows},
        "weapons": {f"weapon.{w}": {"vfx": "", "fireAudio": "", "impactAudio": ""} for w in weapons},
    }, indent=2) + "\n"


def main():
    ids = [s["id"] for s in R]
    assert len(ids) == len(set(ids)), "duplicate roster ids"
    rows = [derive(s) for s in sorted(R, key=lambda s: s["id"])]
    keys = [r["key"] for r in rows]
    assert len(keys) == len(set(keys)), "duplicate asset keys"
    for r in rows:
        assert len(r["weapons"]) <= 4, r["cls"]
    check = "--check" in sys.argv
    outputs = {HEADER: emit_header(rows), MANIFEST: emit_manifest(rows)}
    with open(DOC, encoding="utf-8") as fh:
        doc = fh.read()
    a, b = doc.index(BEGIN), doc.index(END)
    outputs[DOC] = doc[: a + len(BEGIN)] + "\n" + emit_table(rows) + "\n" + doc[b:]
    stale = []
    for path, text in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != text:
            stale.append(path)
            if not check:
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text)
    if check and stale:
        print("stale generated files:", *stale, sep="\n  ")
        return 1
    print(f"{len(rows)} classes; {'up to date' if not stale else 'wrote ' + str(len(stale)) + ' file(s)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
