#!/usr/bin/env python3
"""Writes remaster/godot/scripts/boot_order.gd: the game's class scripts in a leaves-first compile order (Barclay, WebGPU r7,
19 Nov 2026). The web boot (main.gd) compiles scripts a few per frame behind the Starting panel; loading a script compiles
whatever it references that is not compiled yet in the same call, so compiling galaxy_map.gd first pulled half the game
into one 450-550 ms frame. Compiled dependencies-first, each load only pays for its own script.

Dependencies are found statically (class_name identifiers outside strings and comments, preload/extends paths). Scripts in
a reference cycle are emitted together, smallest first. Run after adding or renaming class scripts:
  python remaster/tools/web/gen_boot_order.py"""
import os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'godot')
SKIP = ('/tests/', '/tools/', 'res://core/', 'res://addons/')


def main():
    files = {}
    for d, _, fs in os.walk(ROOT):
        if '.godot' in d.split(os.sep):
            continue
        for f in fs:
            if f.endswith('.gd'):
                p = os.path.join(d, f)
                rp = 'res://' + os.path.relpath(p, ROOT).replace(os.sep, '/')
                files[rp] = open(p, encoding='utf8', errors='replace').read()
    cls = {}
    for rp, s in files.items():
        m = re.search(r'^class_name\s+(\w+)', s, re.M)
        if m:
            cls[m.group(1)] = rp
    deps = {}
    for rp, s in files.items():
        body = re.sub(r'#.*', '', re.sub(r'"(?:[^"\\n]|\.)*"', '""', s))
        ds = {cls[w] for w in set(re.findall(r'\b([A-Z]\w+)\b', body)) if w in cls and cls[w] != rp}
        ds |= {q for q in re.findall(r'(?:preload|extends)\s*\(?\s*"(res://[^"]+\.gd)"', s) if q in files}
        deps[rp] = ds
    sys.setrecursionlimit(20000)
    idx, low, st, on, out, c = {}, {}, [], set(), [], [0]

    def visit(v):
        idx[v] = low[v] = c[0]; c[0] += 1; st.append(v); on.add(v)
        for w in sorted(deps[v]):
            if w not in idx:
                visit(w); low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], idx[w])
        if low[v] == idx[v]:
            comp = []
            while True:
                w = st.pop(); on.discard(w); comp.append(w)
                if w == v:
                    break
            out.append(sorted(comp, key=lambda x: files[x].count('\n')))
    for v in sorted(files):
        if v not in idx:
            visit(v)
    order = [p for comp in out for p in comp if p in cls.values() and not any(k in p for k in SKIP)]
    lines = ['## Generated by remaster/tools/web/gen_boot_order.py (leaves-first compile order for the web boot). Do not edit.',
             'const ORDER: PackedStringArray = [']
    lines += ['\t"%s",' % p for p in order] + [']', '']
    open(os.path.join(ROOT, 'scripts', 'boot_order.gd'), 'w', encoding='utf8', newline='\n').write('\n'.join(lines))
    print(len(order), 'scripts ->', 'scripts/boot_order.gd')


if __name__ == '__main__':
    main()
