#!/usr/bin/env python3
"""Build a BOTF Remastered content pack (docs/DATA-FORMAT.md).

    python remaster/tools/content/build_pack.py            # data/base/ -> data/base.pack.json + ContentBase.generated.h
    python remaster/tools/content/build_pack.py --check    # exit 1 if any output (or a section file) is stale
    python remaster/tools/content/build_pack.py --pack data/mymod --out data/mymod.pack.json   # a mod pack (no header)

The section files are rewritten in canonical form (keys in schema order, one record per line), the bundle is the
merged canonical document the core reads, and the header embeds the base bundle so a host that installs nothing
still gets the base pack. The checksum printed is the core's: 64-bit FNV-1a over the bundle bytes.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "data")
HEADER = os.path.join(ROOT, "game", "Source", "BotfSim", "ContentBase.generated.h")
FORMAT = 1

# Key order per record (also the canonical order). Nested objects list their own order.
SCHEMA = {
    "technologies": ["id", "name", "field", "level", "cost", "description"],
    "ships": ["id", "raceId", "name", "shipClass", "technologyRequirements", "industryCost", "maintenance", "hull",
              "shields", "attack", "range", "speed", "role", "troopCapacity", "description"],
    "buildings": ["id", "name", "technologyField", "technologyLevel", "industryCost", "energyCost", "populationCost",
                  "moraleBonus", "excludedEmpireMask", "residentRaceMask", "bonusType", "bonusValues", "unrestBonuses",
                  "description"],
    "races": ["id", "name", "icon"],
    "roster": ["id", "assetKey", "faction", "raceId", "minorRaceId", "roleName", "className", "hullRole", "engineRole",
               "era", "tier", "technologyRequirements", "industryCost", "buildTurns", "maintenance", "hull", "shields",
               "attack", "torpedoSharePercent", "weapons", "weaponCount", "speed", "range", "sensors", "cloak",
               "sourceKind", "source", "buildable", "description", "flight"],
    "minors": ["id", "name", "homeworld", "referenceRaceId", "temperament", "techLevel", "population", "bonus",
               "bonusValue", "signatureShipId", "affinity", "description"],
    "events": ["kind", "name", "defaultChoice", "choices", "description"],
}
NESTED = {"weapons": ["type", "count", "arc"], "flight": ["turnRate", "acceleration", "lateral", "size"],
          "choices": ["label", "effect"],
          "major": ["empireId", "key", "empireName", "capital", "shipDonor", "traits", "startingFleet"]}
# Keys a record may omit (schema 17: a race that is a playable major carries a `major` block).
OPTIONAL = {"races": ["major"]}
SECTIONS = list(SCHEMA)
PACK_KEYS = ["format", "id", "name", "revision"]


def fail(msg: str) -> None:
    print(f"build_pack: {msg}", file=sys.stderr)
    sys.exit(1)


def ordered(value, keys, where, optional=()):
    if not isinstance(value, dict):
        fail(f"{where}: expected an object")
    present = [k for k in keys if k in value or k not in optional]
    if set(value) != set(present):
        fail(f"{where}: keys {sorted(set(value) ^ set(present))} missing or unknown")
    out = {}
    for k in present:
        v = value[k]
        if k in NESTED:
            if isinstance(v, list):
                v = [ordered(x, NESTED[k], f"{where}.{k}[{i}]") for i, x in enumerate(v)]
            else:
                v = ordered(v, NESTED[k], f"{where}.{k}")
        out[k] = v
    return out


def dump(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def section_text(name, records) -> str:
    return "{\"" + name + "\":[\n" + ",\n".join(dump(r) for r in records) + "\n]}\n"


def bundle_text(meta, sections) -> str:
    head = "{" + ",".join(f"\"{k}\":{dump(meta[k])}" for k in PACK_KEYS)
    body = "".join(",\n\"" + name + "\":[\n" + ",\n".join(dump(r) for r in sections[name]) + "\n]" for name in SECTIONS)
    return head + body + "\n}\n"


def fnv1a64(data: bytes) -> int:
    h = 14695981039346656037
    for b in data:
        h ^= b
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def c_literal(line: bytes) -> str:
    out = []
    for b in line:
        if b == 0x5C: out.append("\\\\")
        elif b == 0x22: out.append("\\\"")
        elif b == 0x0A: out.append("\\n")
        elif 0x20 <= b < 0x7F and b != 0x3F: out.append(chr(b))  # '?' escaped: no trigraph surprises
        else: out.append(f"\\{b:03o}")
    return "\"" + "".join(out) + "\""


def header_text(bundle: bytes, checksum: int) -> str:
    lines = bundle.split(b"\n")
    pieces = [line + b"\n" for line in lines[:-1]]
    if lines[-1]: pieces.append(lines[-1])
    body = ",\n".join("    " + c_literal(p) for p in pieces)
    return ("// GENERATED by remaster/tools/content/build_pack.py from remaster/data/base -- do not edit by hand.\n"
            "// The base content pack (docs/DATA-FORMAT.md), embedded so a host that installs no pack still runs.\n"
            f"// Bundle: {len(bundle)} bytes, FNV-1a 64 checksum {checksum:016x}.\n"
            "// Included by exactly one translation unit (Simulation.cpp).\n"
            "#pragma once\n#include <cstddef>\n\n"
            "namespace botf::content::embedded {\n"
            f"inline constexpr std::size_t BaseBundleBytes = {len(bundle)};\n"
            "inline constexpr const char* BaseBundleLines[] = {\n" + body + "\n};\n"
            "} // namespace botf::content::embedded\n")


def load_pack(folder):
    with open(os.path.join(folder, "pack.json"), encoding="utf-8") as fh:
        meta = json.load(fh)
    files = meta.pop("files", None)
    if files != [f"{s}.json" for s in SECTIONS]:
        fail(f"{folder}/pack.json: files must be {[f'{s}.json' for s in SECTIONS]}")
    meta = ordered(meta, PACK_KEYS, "pack.json")
    if meta["format"] != FORMAT:
        fail(f"pack.json: format {meta['format']} is not {FORMAT}")
    sections = {}
    for name in SECTIONS:
        path = os.path.join(folder, f"{name}.json")
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        if not isinstance(doc, dict) or list(doc) != [name] or not isinstance(doc[name], list):
            fail(f"{path}: expected {{\"{name}\": [...]}}")
        keys = SCHEMA[name] + OPTIONAL.get(name, [])
        sections[name] = [ordered(r, keys, f"{name}[{i}]", OPTIONAL.get(name, ())) for i, r in enumerate(doc[name])]
    return meta, sections, files


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack", default=os.path.join(DATA, "base"))
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    folder = os.path.abspath(a.pack)
    is_base = os.path.normcase(folder) == os.path.normcase(os.path.join(DATA, "base"))
    out = a.out or (os.path.join(DATA, "base.pack.json") if is_base else folder.rstrip("\\/") + ".pack.json")
    meta, sections, files = load_pack(folder)
    if is_base and meta["id"] != "botf-base":
        fail("the base pack id must be botf-base")
    if not is_base and meta["id"] == "botf-base":
        fail("botf-base is reserved for the base pack")
    bundle = bundle_text(meta, sections).encode("utf-8")
    checksum = fnv1a64(bundle)
    outputs = {out: bundle}
    for name in SECTIONS:
        outputs[os.path.join(folder, f"{name}.json")] = section_text(name, sections[name]).encode("utf-8")
    meta_out = dict(meta); meta_out["files"] = files
    outputs[os.path.join(folder, "pack.json")] = (json.dumps(meta_out, ensure_ascii=False, indent=1) + "\n").encode("utf-8")
    if is_base:
        outputs[HEADER] = header_text(bundle, checksum).encode("utf-8")
    stale = []
    for path, data in outputs.items():
        current = open(path, "rb").read() if os.path.exists(path) else None
        if current != data:
            stale.append(os.path.relpath(path, ROOT))
            if not a.check:
                with open(path, "wb") as fh:
                    fh.write(data)
    counts = ", ".join(f"{n} {len(sections[n])}" for n in SECTIONS)
    print(f"pack {meta['id']} r{meta['revision']}: {counts}; {len(bundle)} bytes; checksum {checksum:016x}")
    if a.check:
        if stale:
            print("stale: " + ", ".join(stale))
            sys.exit(1)
        print("up to date")
    else:
        print("wrote: " + (", ".join(stale) if stale else "nothing (up to date)"))


if __name__ == "__main__":
    main()
