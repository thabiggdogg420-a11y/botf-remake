#!/usr/bin/env python3
"""Embed the shipped overlay packs and presets in the core (docs/design/PACKS-AND-PRESETS.md).

    python remaster/tools/content/build_presets.py           # data/overlays + data/presets -> ContentPresets.generated.h
    python remaster/tools/content/build_presets.py --check   # exit 1 if the header is stale or a file is malformed

Each file is embedded byte for byte (the overlay checksum is over its exact bytes, like a bundle's). The core parses
and validates them again at first use; this script only catches the cheap mistakes early (JSON, ids, references).
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "data")
HEADER = os.path.join(ROOT, "game", "Source", "BotfSim", "ContentPresets.generated.h")
ID = re.compile(r"^[a-z0-9-]{1,40}$")


def fail(msg: str) -> None:
    print(f"build_presets: {msg}", file=sys.stderr)
    sys.exit(1)


def c_literal(line: bytes) -> str:
    out = []
    for b in line:
        if b == 0x5C: out.append("\\\\")
        elif b == 0x22: out.append("\\\"")
        elif b == 0x0A: out.append("\\n")
        elif 0x20 <= b < 0x7F and b != 0x3F: out.append(chr(b))
        else: out.append(f"\\{b:03o}")
    return "\"" + "".join(out) + "\""


def collect(kind: str, pattern: str):
    files = sorted(glob.glob(os.path.join(DATA, kind, pattern)))
    out = []
    for path in files:
        raw = open(path, "rb").read()
        if b"\r" in raw:
            fail(f"{path}: contains CR; keep LF line ends (checksums are over exact bytes)")
        try:
            doc = json.loads(raw.decode("utf-8"))
        except ValueError as e:
            fail(f"{path}: {e}")
        name = os.path.basename(path).split(".")[0]
        if not isinstance(doc, dict) or doc.get("id") != name or not ID.match(name):
            fail(f"{path}: id must equal the file name and be [a-z0-9-]")
        out.append((name, raw, doc))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    overlays = collect("overlays", "*.overlay.json")
    presets = collect("presets", "*.preset.json")
    known = {n for n, _, _ in overlays}
    for name, _, doc in presets:
        for ov in doc.get("overlays", []):
            if ov not in known:
                fail(f"preset {name}: overlay {ov} has no file in data/overlays")
    text = ["// GENERATED by remaster/tools/content/build_presets.py from remaster/data/overlays and data/presets -- do not edit.",
            "// Shipped overlay packs and presets, embedded byte for byte (docs/design/PACKS-AND-PRESETS.md).",
            "// Included by exactly one translation unit (Simulation.cpp).",
            "#pragma once", "#include <cstddef>", "", "namespace botf::presets::embedded {",
            "struct File { const char* const* lines; std::size_t count; };"]
    for group, items in (("Overlay", overlays), ("Preset", presets)):
        names = []
        for i, (name, raw, _) in enumerate(items):
            lines = raw.split(b"\n")
            pieces = [l + b"\n" for l in lines[:-1]] + ([lines[-1]] if lines[-1] else [])
            text.append(f"// {name}")
            text.append(f"inline constexpr const char* const {group}{i}[] = {{")
            text.append(",\n".join("    " + c_literal(p) for p in pieces))
            text.append("};")
            names.append(f"{{{group}{i}, sizeof({group}{i}) / sizeof({group}{i}[0])}}")
        text.append(f"inline constexpr File {group}Files[] = {{" + ", ".join(names) + "};")
    text.append("} // namespace botf::presets::embedded")
    body = "\n".join(text) + "\n"
    if a.check:
        have = open(HEADER, encoding="utf-8", newline="").read() if os.path.exists(HEADER) else ""
        if have != body:
            fail("ContentPresets.generated.h is stale; run build_presets.py")
        print(f"build_presets: ok ({len(overlays)} overlays, {len(presets)} presets)")
        return
    with open(HEADER, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"build_presets: wrote {HEADER} ({len(overlays)} overlays, {len(presets)} presets)")


if __name__ == "__main__":
    main()
