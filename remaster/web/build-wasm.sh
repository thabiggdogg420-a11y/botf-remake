#!/usr/bin/env bash
# Builds the deterministic simulation core + JSON bridge to a single ES module with the
# WebAssembly binary embedded (src/generated/botf-core.mjs). The generated module is committed so
# the web app builds without Emscripten; rerun this after changing the core or the bridge.
#
#   ./build-wasm.sh            # incremental (core object cached in .wasm-build/)
#   ./build-wasm.sh --clean    # rebuild everything
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CORE="$HERE/../game/Source/BotfSim"
BRIDGE="$HERE/bridge"
OUT="$HERE/src/generated"
CACHE="$HERE/.wasm-build"

if ! command -v em++ >/dev/null 2>&1; then
  EMSDK_DIR="${EMSDK:-/opt/emsdk}"
  if [[ -f "$EMSDK_DIR/emsdk_env.sh" ]]; then
    # shellcheck disable=SC1091
    source "$EMSDK_DIR/emsdk_env.sh" >/dev/null 2>&1
  fi
fi
command -v em++ >/dev/null 2>&1 || { echo "em++ not found: install/activate emsdk or set EMSDK" >&2; exit 1; }

[[ "${1:-}" == "--clean" ]] && rm -rf "$CACHE"
mkdir -p "$OUT" "$CACHE"

CXXFLAGS=(-std=c++20 -O2 -fexceptions -Wall -Wextra -I"$CORE" -I"$BRIDGE")

needs_build() {  # target, sources...
  local target="$1"; shift
  [[ ! -f "$target" ]] && return 0
  for src in "$@"; do [[ "$src" -nt "$target" ]] && return 0; done
  return 1
}

CORE_HEADERS=("$CORE"/*.h)
if needs_build "$CACHE/Simulation.o" "$CORE/Simulation.cpp" "${CORE_HEADERS[@]}"; then
  echo "[wasm] compiling simulation core (slow: large constexpr catalogues)..."
  em++ "${CXXFLAGS[@]}" -c "$CORE/Simulation.cpp" -o "$CACHE/Simulation.o"
fi
if needs_build "$CACHE/WebBridge.o" "$BRIDGE/WebBridge.cpp" "$BRIDGE/Json.h" "${CORE_HEADERS[@]}"; then
  echo "[wasm] compiling bridge..."
  em++ "${CXXFLAGS[@]}" -c "$BRIDGE/WebBridge.cpp" -o "$CACHE/WebBridge.o"
fi

echo "[wasm] linking ES module..."
em++ -O2 -fexceptions "$CACHE/Simulation.o" "$CACHE/WebBridge.o" -o "$OUT/botf-core.mjs" \
  -sSINGLE_FILE=1 -sMODULARIZE=1 -sEXPORT_ES6=1 -sALLOW_MEMORY_GROWTH=1 \
  -sEXPORT_NAME=createBotfCore -sENVIRONMENT=web,worker,node \
  -sINITIAL_MEMORY=33554432 -sSTACK_SIZE=4194304 \
  -sEXPORTED_FUNCTIONS=_botf_call -sEXPORTED_RUNTIME_METHODS=ccall,cwrap,UTF8ToString \
  -sFILESYSTEM=0

cat > "$OUT/botf-core.d.mts" <<'EOF'
// Generated by build-wasm.sh — typings for the Emscripten ES module.
export interface BotfCoreModule {
  ccall(name: string, returnType: 'string', argTypes: string[], args: unknown[]): string;
  cwrap(name: string, returnType: 'string', argTypes: string[]): (...args: unknown[]) => string;
}
export default function createBotfCore(options?: Record<string, unknown>): Promise<BotfCoreModule>;
EOF

echo "[wasm] wrote $(du -h "$OUT/botf-core.mjs" | cut -f1) -> $OUT/botf-core.mjs"
